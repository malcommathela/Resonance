// ============================================================================
// DESIGN GENERATION VALIDATOR — Chat spec §58-60, §131
// AI output is untrusted input. Pipeline:
//   Gemini -> parse JSON -> schema validation -> structural validation
//     -> graph validation -> security validation -> (DB, by the worker)
// ============================================================================

import { z } from 'zod'
import { AppError, ERROR_CODES } from '../../utils/errors.js'

// Component metadata — mirrors the canvas block library so generated designs
// render identically to hand-built ones (frontend customBlock/customEdge).
